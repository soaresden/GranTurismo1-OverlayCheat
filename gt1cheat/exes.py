def jal(target):
    return 0x0C000000 | ((target >> 2) & 0x03FFFFFF)


def c_header():
    """src/exes.h: the table of cheat.c (struct exe)."""
    out = ['/* generated by build.py from gt1cheat/exes.py: do not edit */']
    for name, macro in (('GTMAIN.EXE', 'EXE_MAIN'), ('GTMENU.EXE', 'EXE_MENU')):   # ids 0, 1
        e = EXES[name]
        sites = [s or (0, 0) for s in e['sites']]
        out.append('#define %s { 0x%08X, 0x%08X, 0x%08X, 0x%08X, 0x%08X, 0x%08X, 0x%08X, { %s }, { %s } }' % (
            macro, e['memcpy'], e['drawsync'], e['drawotag'], e['tick'], e['clock'], e['money'], e['mode'],
            ', '.join('0x%08X' % a for a, _ in sites),
            ', '.join('0x%08X' % (jal(t) if a else 0) for a, t in sites)))
    return '\n'.join(out) + '\n'
