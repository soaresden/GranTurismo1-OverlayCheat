"""What the patch knows of the two executables of Gran Turismo (PAL SCES-00984).

Found by static analysis of the unpacked code (the files are PSLZ-packed; see pslz.py), checked
in PCSX-Redux (see README). The MX-5 mod of the same author leaves both files untouched, so the
same addresses serve the stock disc and the modded one.

    memcpy    the game's memcpy(dst, src, n)
    drawsync  libgpu DrawSync(mode)
    drawotag  libgpu DrawOTag(p) (found by its debug string "DrawOTag(%08x)..."; one caller)
    tick      race clock tick: clock += 20 or 40 ms per frame (GTMAIN only)
    clock     the race clock (u32, ms); never frozen at 0: a licence whose clock never left 0
              does not end (the car stops in the goal area and nothing happens)
    money     credits (u32) in the game status block ("GTos", +0x44)
    mode      game mode byte in GTMAIN (4 = licence test: jump table 0x8008BC68, case
              0x80027E80 leads to "license result menu")
    sites     the `jal` redirected by cheat_boot, in this order: pad copy (raw pad buffers ->
              the copy the game reads, once per game frame), DrawOTag of the frame (its only
              caller), clock tick (GTMAIN only); each is (address of the jal, its target).
    loader    PSLZ header +0x10: where the loader copies itself, and so the stub
    piece     which piece of the resident block the stub carries and copies (0: GTOS.EXE, run
              once at start-up before the menus; 1: GTMENU.EXE): the block (~2.5 KB) does not
              fit in the free bytes of a single executable
    boot      the stub calls cheat_boot(id) (GTMAIN, GTMENU)
    room      zero bytes after the loader, up to the end of the file (684 / 1820 / 1224)
"""

RESIDENT = 0x8000F000      # resident block (BIOS kernel heap ends near 0x8000E500)
STATE = 0x8000FF80         # struct g of cheat.c (not part of the copied block)
GAME_ENTRY = 0x80010000    # where the PSLZ loader jumps once the game is unpacked
